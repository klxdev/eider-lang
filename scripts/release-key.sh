#!/bin/sh
# The release signing key (docs/site/tooling/releases.md, "Keys"): a minisign-compatible
# Ed25519 keypair. The secret key never goes into a repository.
#
#   sh scripts/release-key.sh            generate the keypair (once), then embed its public key
#   sh scripts/release-key.sh --embed    only embed the existing key's public key again
#   sh scripts/release-key.sh --print    print the existing key's public key file
#
# The secret key is $EIDER_RELEASE_KEY, default ~/.config/eider/release.key, mode 0600 in a
# 0700 directory. It is NOT encrypted (minisign's KDF is set to none, as `minisign -G -W`
# writes), so publishing needs no passphrase: the file's permissions and the machine are its
# only protection. Back it up somewhere offline; without it no further release can be signed
# with this key, and a new key means every installed `eider` must be updated by hand.
# The public key goes next to it (release.pub), and is embedded in `eider` through the
# generated packages/eider/release_key.ei, in packages/eider/release.pub (for minisign
# users) and in install.sh: commit those three files.
#
# Refuses to overwrite an existing secret key. Needs what scripts/eider needs to build
# target/eider-sign (a C compiler and the AWS-LC sources: sh scripts/fetch-awslc.sh).
cd "$(dirname "$0")/.." || exit 1
die() { echo "release-key: $*" >&2; exit 1; }
key=${EIDER_RELEASE_KEY:-${XDG_CONFIG_HOME:-$HOME/.config}/eider/release.key}
pub=${key%.key}.pub
[ "$pub" = "$key" ] && pub=$key.pub
mode=generate
case ${1:-} in
  "") ;;
  --embed) mode=embed ;;
  --print) mode=print ;;
  *) echo "usage: sh scripts/release-key.sh [--embed | --print]" >&2; exit 2 ;;
esac
sh scripts/eider --build-only || die "cannot build target/eider-sign"
sign=target/eider-sign

if [ $mode = generate ]; then
  [ -e "$key" ] && die "$key exists already: the release key is generated once (--embed embeds its public key again; move it away first to make a new key)"
  dir=$(dirname "$key")
  mkdir -p "$dir" && chmod 700 "$dir" || die "cannot create $dir"
  (umask 077 && "$sign" keygen "$key" "$pub") >/dev/null || die "eider-sign keygen failed"
  chmod 600 "$key" || die "chmod 600 $key failed"
  chmod 644 "$pub"
  echo "release-key: wrote the secret key $key (mode 0600, unencrypted: back it up offline)"
  echo "release-key: wrote the public key $pub"
fi
[ -f "$key" ] || die "no secret key at $key (sh scripts/release-key.sh generates it)"
perm=$(stat -c %a "$key" 2>/dev/null || stat -f %Lp "$key")
[ "$perm" = 600 ] || die "$key has mode $perm; it must be 600 (chmod 600 $key)"
# the public key from the secret key itself (its checksum is checked on the way)
"$sign" pubkey "$key" > target/release-key.pub || die "cannot read $key"
if [ $mode = print ]; then cat target/release-key.pub; exit 0; fi
line=$(sed -n 2p target/release-key.pub)
id=$(sed -n '1s/.*minisign public key //p' target/release-key.pub)
[ -n "$line" ] && [ -n "$id" ] || die "unexpected public key format"

cat > packages/eider/release_key.ei <<EOF
// release_key: the public key that signs Eider's releases, embedded in \`eider\`.
// Generated by scripts/release-key.sh; do not edit. EIDER_RELEASE_PUBKEY overrides it
// (a minisign public key line, or a .pub file), for testing.

/// The minisign public key (its base64 line).
pub const PUBLIC_KEY: str = "$line"
/// Its key id, as minisign prints it.
pub const KEY_ID: str = "$id"
EOF
cp target/release-key.pub packages/eider/release.pub
# install.sh carries the key too (it checks the signature before anything runs)
sed "s|^EIDER_PUBKEY=.*|EIDER_PUBKEY=$line|" install.sh > install.sh.new && mv install.sh.new install.sh && chmod 755 install.sh
grep -q "^EIDER_PUBKEY=$line\$" install.sh || die "could not write the key into install.sh"
echo "release-key: embedded key $id in packages/eider/release_key.ei, packages/eider/release.pub and install.sh:"
cat target/release-key.pub
