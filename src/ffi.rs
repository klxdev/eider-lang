//! C interop: `extern "c"` declarations, `unsafe`, `export fn`, and the generated C header.

use crate::ast::*;
use crate::check::*;
use std::collections::HashSet;

impl<'a> Checker<'a> {
    fn ffi_safe(&self, t: &Ty, is_ret: bool, allow_records: bool) -> bool {
        match t {
            Ty::Int(_) | Ty::Bool | Ty::Str => true,
            Ty::Unit => is_ret,
            Ty::Record(k) => allow_records && self.rec_defs[k].fields.iter().all(|(_, ft)| self.ffi_safe(ft, false, true)),
            _ => false,
        }
    }

    pub fn check_ffi_sig(&self, decl: &FnDecl, sig: &Sig) -> R<()> {
        let what = if decl.is_extern { "extern \"c\"" } else { "export" };
        let allow_records = decl.is_export && self.mode != Mode::Wasm;
        if decl.is_export && self.mode == Mode::Wasm {
            for ((n, _, t), p) in sig.params.iter().zip(decl.params.iter()) {
                if !matches!(t, Ty::Int(_) | Ty::Bool) {
                    return err("E0806", p.pos, format!("parameter `{}` has type {}; WebAssembly exports take only integers and bool", n, t));
                }
            }
            if !matches!(sig.ret, Ty::Int(_) | Ty::Bool | Ty::Unit) {
                return err("E0806", decl.pos, format!("return type {} isn't supported for WebAssembly exports (integers, bool, or ())", sig.ret));
            }
        }
        for ((n, inout, t), p) in sig.params.iter().zip(decl.params.iter()) {
            if *inout {
                return err("E0803", p.pos, format!("`{}` is `inout`; {} functions can't take `inout` parameters", n, what));
            }
            if !self.ffi_safe(t, false, allow_records) {
                return err("E0803", p.pos, format!("parameter `{}` has type {}, which can't cross the C boundary", n, t))
                    .map_err(|d| d.help("C-safe types: integers, bool, str (const char*), and records made only of those (export only)"));
            }
        }
        if !self.ffi_safe(&sig.ret, true, allow_records) {
            return err("E0803", decl.pos, format!("return type {} can't cross the C boundary", sig.ret))
                .map_err(|d| d.help("C-safe types: integers, bool, str (const char*), and records made only of those (export only)"));
        }
        Ok(())
    }

    fn ts_ty(&self, t: &Ty) -> &'static str {
        match t {
            Ty::Bool => "boolean",
            Ty::Unit => "void",
            _ => {
                let c = self.ctype(t);
                if c.contains("64") { "bigint" } else { "number" }
            }
        }
    }

    /// TypeScript declarations for the exports (WebAssembly mode).
    pub fn ts_decls(&self) -> String {
        let mut s = String::from("// generated by eider\nexport interface EiderExports {\n");
        for (name, sig) in &self.exports {
            let ps: Vec<String> = sig.params.iter().map(|(n, _, t)| format!("{}: {}", n, self.ts_ty(t))).collect();
            s.push_str(&format!("  {}({}): {};\n", name, ps.join(", "), self.ts_ty(&sig.ret)));
        }
        s.push_str("}\nexport interface EiderImports { [name: string]: (...args: any[]) => any }\nexport function load(wasm: BufferSource | WebAssembly.Module, imports?: EiderImports): Promise<EiderExports>;\n");
        s
    }

    /// JS loader: instantiates the module, supplies the runtime imports, wraps the exports.
    pub fn js_loader(&self, wasm_file: &str) -> String {
        let mut w = String::new();
        for (name, sig) in &self.exports {
            let args: Vec<String> = sig.params.iter().map(|(n, _, _)| n.clone()).collect();
            let call = format!("x.eider_{}({})", name, args.join(", "));
            let call = if sig.ret == Ty::Bool { format!("!!{}", call) } else { call };
            w.push_str(&format!("    {}: ({}) => {},\n", name, args.join(", "), call));
        }
        format!(
            "// generated by eider: loader for {wasm}\nexport async function load(wasm, imports = {{}}) {{\n  let mem;\n  const dec = new TextDecoder();\n  const env = {{\n    eider_write(p, n) {{ (typeof process !== 'undefined' ? process.stdout.write.bind(process.stdout) : console.log)(dec.decode(new Uint8Array(mem.buffer, p, n))); }},\n    eider_now_ms() {{ return BigInt(Date.now()); }},\n    ...imports,\n  }};\n  const src = wasm instanceof WebAssembly.Module ? wasm : await WebAssembly.compile(wasm);\n  const inst = await WebAssembly.instantiate(src, {{ env }});\n  mem = inst.exports.memory;\n  const x = inst.exports;\n  return {{\n{w}  }};\n}}\n",
            wasm = wasm_file, w = w
        )
    }

    /// C header for the exported functions (empty unless building a library).
    pub fn header(&mut self) -> String {
        if self.mode == Mode::Wasm {
            return format!("{}\u{1}{}", self.ts_decls(), self.js_loader("@WASM@"));
        }
        if self.mode != Mode::Lib {
            return String::new();
        }
        let mut defs = String::new();
        let mut done = HashSet::new();
        let mut protos = String::new();
        for (name, sig) in self.exports.clone() {
            let mut tys: Vec<Ty> = sig.params.iter().map(|p| p.2.clone()).collect();
            tys.push(sig.ret.clone());
            for t in tys {
                if let Ty::Record(_) = t {
                    let ct = self.ctype(&t);
                    if !done.contains(&ct) {
                        defs.push_str(&format!("typedef struct {k} {k};\n", k = ct));
                    }
                    self.def_ty(&t, &mut done, &mut defs);
                }
            }
            let params: Vec<String> = sig.params.iter().map(|(n, _, t)| format!("{} {}", self.ctype(t), n)).collect();
            protos.push_str(&format!("{} eider_{}({});\n", self.ctype(&sig.ret), name, if params.is_empty() { "void".to_string() } else { params.join(", ") }));
        }
        format!(
            "/* generated by eider: C interface */\n#ifndef EIDER_EXPORTS_H\n#define EIDER_EXPORTS_H\n#include <stdint.h>\n#include <stdbool.h>\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n{}{}#ifdef __cplusplus\n}}\n#endif\n#endif\n",
            defs, protos
        )
    }
}
